/* test-dropin.c — check the drop-in fixate.c writes, byte for byte.
 *
 * This is the part of the generator that matters and the only part that can be
 * tested without a TPM: if the ExecStart it emits is wrong in any way, the root
 * does not open, and the failure appears as a cryptsetup unit failing in the
 * initrd with the console saying nothing about why. There is no second chance to
 * notice, because the machine is a brick until someone types a passphrase, and on
 * a first boot there is no passphrase.
 *
 * So the expected output is pinned here rather than eyeballed, including the two
 * details that are easy to get wrong and impossible to notice:
 *
 *   - the empty "ExecStart=" that resets the vendor list. Without it both
 *     ExecStarts are in the unit and the unit does not load.
 *   - specifier escaping, '%' doubled. systemd expands an unescaped '%' as a
 *     specifier, so a crypttab device path containing one would be silently
 *     mangled. specifier_escape() is a plain strreplace(" %", "%%")
 *     (specifier.c:430-432) and this reproduces it.
 *
 * Build: make test
 */

#define _GNU_SOURCE

#include "fixate.h"
#include "nvindex.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

static int failures;

static void check(const char *what, const char *got, const char *want) {
        if (strcmp(got, want) == 0) {
                printf("  ok   %s\n", what);
                return;
        }
        printf("  FAIL %s\n    want: %s\n    got:  %s\n", what, want, got);
        failures++;
}

/* Read a whole file into a NUL-terminated buffer.
 *
 * The first version of this used getline(), which reads ONE line. The drop-in is
 * a dozen lines whose first line is a comment, so every comparison was against
 * "# Generated by vngrd-fixate-generator. Do not edit." and the test reported the
 * writer as producing nothing. Reading the file is not the place to be clever.
 */
static char *slurp(const char *path) {
        FILE *f = fopen(path, "re");
        if (f == NULL)
                return NULL;

        if (fseek(f, 0, SEEK_END) != 0) {
                fclose(f);
                return NULL;
        }
        long len = ftell(f);
        if (len < 0) {
                fclose(f);
                return NULL;
        }
        rewind(f);

        char *buf = malloc((size_t) len + 1);
        if (buf == NULL) {
                fclose(f);
                return NULL;
        }
        size_t got = fread(buf, 1, (size_t) len, f);
        buf[got] = '\0';
        fclose(f);
        return buf;
}

static void write_crypttab(const char *path, const char *content) {
        FILE *f = fopen(path, "we");
        if (f == NULL) {
                perror(path);
                exit(2);
        }
        fputs(content, f);
        fclose(f);
}

/* The crypttab the image actually ships, from
 * packages/base-files/files/usr/share/factory/etc/crypttab. Copied rather than
 * referenced so the test fails if that file changes shape, which is the point.
 */
static const char CRYPTTAB_REAL[] =
        "# <comment>\n"
        "\n"
        "vngrd-root /dev/disk/by-partlabel/vngrd-root none tpm2-device=auto,x-initrd.attach\n";

int main(void) {
        char dir[] = "/tmp/vngrd-fixate-test.XXXXXX";
        if (mkdtemp(dir) == NULL) {
                perror("mkdtemp");
                return 2;
        }

        char crypttab[512], dropin[512];
        snprintf(crypttab, sizeof(crypttab), "%s/crypttab", dir);
        snprintf(dropin, sizeof(dropin), "%s/systemd-cryptsetup@vngrd-root.service.d/50-vngrd-fixate.conf", dir);
        write_crypttab(crypttab, CRYPTTAB_REAL);

        const char *hex = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";

        /* --- 1. the real line ------------------------------------------------ */
        FixateCrypttabEntry entry;
        int found = fixate_crypttab_lookup(crypttab, "vngrd-root", &entry);
        if (found != 1) {
                printf("  FAIL lookup returned %d, expected 1\n", found);
                return 1;
        }
        check("name", entry.name, "vngrd-root");
        check("device", entry.device, "/dev/disk/by-partlabel/vngrd-root");
        check("keyfile", entry.keyfile, "none");
        check("options", entry.options, "tpm2-device=auto,x-initrd.attach");

        if (fixate_write_dropin(dropin, &entry, hex) < 0) {
                printf("  FAIL write_dropin returned an error\n");
                return 1;
        }

        char *got = slurp(dropin);
        if (got == NULL) {
                printf("  FAIL could not read the drop-in back\n");
                return 1;
        }

        char want[2048];
        snprintf(want, sizeof(want),
                 "# Generated by vngrd-fixate-generator. Do not edit.\n"
                 "#\n"
                 "# Re-runs the cryptsetup attach with fixate-volume-key set, so the volume\n"
                 "# key the TPM just released is checked against the digest frozen in NV index\n"
                 "# 0x1C00000 as provisioning. A substituted volume produces a different digest and\n"
                 "# is refused before activation. Reproduced from the ExecStart that\n"
                 "# systemd-cryptsetup-generator wrote (generator.c:977-981), with the option\n"
                 "# appended to the crypttab's own options.\n"
                 "[Service]\n"
                 "ExecStart=\n"
                 "ExecStart=/usr/bin/systemd-cryptsetup attach 'vngrd-root' "
                 "'/dev/disk/by-partlabel/vngrd-root' 'none' "
                 "'tpm2-device=auto,x-initrd.attach,fixate-volume-key=%s'\n",
                 hex);

        /* The comment block is prose and is allowed to change; what is pinned is
         * everything from [Service] down, which is what systemd parses. So
         * compare the tail rather than the whole file. */
        char *got_service = strstr(got, "[Service]");
        char *want_service = strstr(want, "[Service]");
        if (got_service == NULL || want_service == NULL) {
                printf("  FAIL no [Service] section in the drop-in\n");
                printf("    got: %s\n", got);
                return 1;
        }
        check("drop-in body (from [Service])", got_service, want_service);

        /* --- 2. an empty options field must not gain a leading comma -------- */
        {
                char c2[512], d2[512];
                snprintf(c2, sizeof(c2), "%s/crypttab2", dir);
                snprintf(d2, sizeof(d2), "%s/x2/50-vngrd-fixate.conf", dir);
                write_crypttab(c2, "vngrd-root /dev/vg none\n");

                FixateCrypttabEntry e2;
                if (fixate_crypttab_lookup(c2, "vngrd-root", &e2) != 1) {
                        printf("  FAIL lookup of the no-options line failed\n");
                        return 1;
                }
                if (fixate_write_dropin(d2, &e2, hex) < 0) {
                        printf("  FAIL write_dropin on the no-options line\n");
                        return 1;
                }
                char *g2 = slurp(d2);
                if (g2 != NULL && strstr(g2, "',fixate-volume-key=") != NULL) {
                        printf("  FAIL a leading comma appeared in the options list:\n    %s\n", g2);
                        failures++;
                } else {
                        printf("  ok   no leading comma when the crypttab options field is empty\n");
                }
                free(g2);
                fixate_crypttab_entry_done(&e2);
        }

        /* --- 3. '%' in a field must be doubled ------------------------------ */
        {
                char c3[512], d3[512];
                snprintf(c3, sizeof(c3), "%s/crypttab3", dir);
                snprintf(d3, sizeof(d3), "%s/x3/50-vngrd-fixate.conf", dir);
                write_crypttab(c3, "vngrd-root /dev/disk/by-uuid/1234-%%-abcd none tpm2-device=auto\n");

                FixateCrypttabEntry e3;
                if (fixate_crypttab_lookup(c3, "vngrd-root", &e3) != 1) {
                        printf("  FAIL lookup of the percent line failed\n");
                        return 1;
                }
                if (fixate_write_dropin(d3, &e3, hex) < 0) {
                        printf("  FAIL write_dropin on the percent line\n");
                        return 1;
                }
                char *g3 = slurp(d3);
                /* '%%' in the crypttab input above is a literal '%%', so the file
                 * contains two percent characters and systemd needs four. */
                if (g3 != NULL && strstr(g3, "1234-%%%%-abcd") == NULL) {
                        printf("  FAIL '%%' was not escaped:\n    %s\n", g3 != NULL ? g3 : "(null)");
                        failures++;
                } else {
                        printf("  ok   '%%' doubled in the device field\n");
                }
                free(g3);
                fixate_crypttab_entry_done(&e3);
        }

        /* --- 4. a wrong-length digest is refused ---------------------------- */
        {
                char d4[512];
                snprintf(d4, sizeof(d4), "%s/x4/50-vngrd-fixate.conf", dir);
                if (fixate_write_dropin(d4, &entry, "abcd") == 0) {
                        printf("  FAIL a 4-hex-digit digest was accepted\n");
                        failures++;
                } else {
                        printf("  ok   a wrong-length digest is refused rather than written\n");
                }
        }

        /* --- 5. a name that is not in the crypttab ------------------------- */
        {
                FixateCrypttabEntry e5;
                if (fixate_crypttab_lookup(crypttab, "some-other-volume", &e5) != 0) {
                        printf("  FAIL lookup of an absent volume did not return 0\n");
                        failures++;
                } else {
                        printf("  ok   an absent volume returns 0, not an error\n");
                }
                fixate_crypttab_entry_done(&e5);
        }

        /* --- 6. a line with a name but no device is refused ----------------- */
        {
                char c6[512];
                snprintf(c6, sizeof(c6), "%s/crypttab6", dir);
                write_crypttab(c6, "vngrd-root\n");
                FixateCrypttabEntry e6;
                if (fixate_crypttab_lookup(c6, "vngrd-root", &e6) >= 0) {
                        printf("  FAIL a device-less line was accepted\n");
                        failures++;
                } else {
                        printf("  ok   a device-less line is refused\n");
                }
                fixate_crypttab_entry_done(&e6);
        }

        free(got);
        fixate_crypttab_entry_done(&entry);

        char cmd[600];
        snprintf(cmd, sizeof(cmd), "rm -rf '%s'", dir);
        if (system(cmd) != 0)
                printf("  note: could not clean up %s\n", dir);

        if (failures > 0) {
                printf("\n%d check(s) failed\n", failures);
                return 1;
        }
        printf("\nall drop-in checks passed\n");
        return 0;
}

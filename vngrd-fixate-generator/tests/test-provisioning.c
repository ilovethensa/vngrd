/* test-provisioning.c — the "did this boot create the root" predicate.
 *
 * The predicate is not an existence check. systemd-repart rewrites
 * /run/vngrd/repart-crypttab on every boot because its definition carries
 * EncryptedVolume=, and only the format path appends fixate-volume-key=. If the
 * guards treated mere existence as the provisioning marker, every later boot
 * would look like the provisioning boot and an absent index would pass.
 *
 * Pure libc, no TPM and no disk: cases are files in a tempdir.
 *
 * Build: make test
 */

#define _GNU_SOURCE

#include "provisioning.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

static int failures;
static char dir[] = "/tmp/vngrd-provisioning-XXXXXX";
static char path[sizeof(dir) + 32];

static void expect(const char *label, bool want) {
        bool got = provisioning_marker_present(path);

        if (got == want) {
                printf("  ok   %s\n", label);
                return;
        }

        printf("  FAIL %s: want %s, got %s\n", label, want ? "true" : "false",
               got ? "true" : "false");
        failures++;
}

static void write_case(const char *content) {
        FILE *f = fopen(path, "we");

        if (f == NULL) {
                perror("fopen");
                exit(1);
        }
        if (content != NULL && fputs(content, f) == EOF) {
                perror("fputs");
                exit(1);
        }
        if (fclose(f) != 0) {
                perror("fclose");
                exit(1);
        }
}

int main(void) {
        if (mkdtemp(dir) == NULL) {
                perror("mkdtemp");
                return 1;
        }
        snprintf(path, sizeof(path), "%s/crypttab", dir);

        printf("test-provisioning: marker content\n");

        expect("missing file", false);

        write_case("");
        expect("empty file", false);

        write_case("# generated by systemd-repart\n"
                   "vngrd-root UUID=11111111-2222-3333-4444-555555555555 "
                   "/dev/disk/by-partlabel/vngrd-root none luks\n");
        expect("later-boot crypttab without the option", false);

        write_case("vngrd-root UUID=11111111-2222-3333-4444-555555555555 "
                   "/dev/disk/by-partlabel/vngrd-root none "
                   "luks,discard,fixate-volume-key=00112233\n");
        expect("provisioning crypttab", true);

        write_case("fixate-volume-key=00112233\n");
        expect("option on its own line", true);

        write_case("fixate-volume-key\n");
        expect("option name without '='", false);

        write_case("vngrd-root UUID=... fixate-volume-key=abc\n"
                   "vngrd-root UUID=... fixate-volume-key=def\n");
        expect("second matching line", true);

        if (unlink(path) != 0) {
                perror("unlink");
                return 1;
        }
        if (rmdir(dir) != 0) {
                perror("rmdir");
                return 1;
        }

        if (failures != 0) {
                printf("test-provisioning: %d failure(s)\n", failures);
                return 1;
        }

        printf("test-provisioning: all cases pass\n");
        return 0;
}
